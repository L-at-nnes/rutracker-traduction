  const UNIT_RE = new RegExp("(\\d+)\\s+(" + Object.keys(UNIT_BASE).join("|") + ")(?![а-яёА-ЯЁa-zA-Z])", "g");

  const SKIP_SELECTOR = ".tLink, .torTopic, #topic-title, .postbody, .post_body, .msgtxt, .spoiler_text";

  function translateDuration(text) {
    let changed = false;
    const result = text.replace(UNIT_RE, (_full, num, word) => {
      changed = true;
      const base = UNIT_BASE[word];
      const n = parseInt(num, 10);
      return num + " " + base + (n === 1 ? "" : "s");
    });
    return changed ? result : null;
  }

  function lookup(trimmed) {
    if (DICT.hasOwnProperty(trimmed)) return DICT[trimmed];

    if (trimmed.startsWith("|- ")) {
      const rest = trimmed.slice(3).trim();
      if (DICT.hasOwnProperty(rest)) return "|- " + DICT[rest];
    }

    for (const prefix in PREFIX_DICT) {
      if (trimmed.startsWith(prefix)) {
        return PREFIX_DICT[prefix] + trimmed.slice(prefix.length);
      }
    }

    const dateMatch = trimmed.match(DATE_RE);
    if (dateMatch) {
      return trimmed.replace(dateMatch[2], MONTH_DICT[dateMatch[2]]);
    }

    const durationMatch = translateDuration(trimmed);
    if (durationMatch !== null) return durationMatch;

    return null;
  }

  function translateTextNode(node) {
    const raw = node.textContent;
    const trimmed = raw.trim();
    if (!trimmed) return;
    const translated = lookup(trimmed);
    if (translated === null) return;
    const lead = raw.match(/^\s*/)[0];
    const trail = raw.match(/\s*$/)[0];
    const newText = lead + translated + trail;
    if (newText !== raw) node.textContent = newText;
  }

  function translateAttr(el, attr) {
    const val = el.getAttribute(attr);
    if (!val) return;
    const trimmed = val.trim();
    const translated = lookup(trimmed);
    if (translated !== null && translated !== val) {
      el.setAttribute(attr, translated);
    }
  }

